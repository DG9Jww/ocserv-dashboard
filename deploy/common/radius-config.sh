#!/usr/bin/env bash

ocserv_auth_method() {
    awk '
        /^[[:space:]]*auth[[:space:]]*=/ {
            count++
            sub(/^[^=]*=[[:space:]]*/, "")
            sub(/#.*/, "")
            sub(/[[:space:]]+$/, "")
            if ($0 ~ /^"certificate"$/ || $0 == "certificate") method = "certificate"
            else if ($0 ~ /^"radius\[.*\]"$/ || $0 ~ /^radius\[.*\]$/) method = "radius"
        }
        /^[[:space:]]*enable-auth[[:space:]]*=/ {
            alternatives++
            sub(/^[^=]*=[[:space:]]*/, "")
            sub(/#.*/, "")
            sub(/[[:space:]]+$/, "")
            if ($0 ~ /^"certificate"$/ || $0 == "certificate") certificate++
        }
        END {
            if (count != 1 || method == "") exit 1
            if (method == "radius" && alternatives) {
                if (alternatives != 1 || certificate != 1) exit 1
                method = "radius-certificate"
            }
            print method
        }
    ' "$1"
}

# Remove the password fallback from configurations generated by older releases.
# A custom fallback requires an explicit edit before switching authentication.
certificate_ocserv_config_ready() {
    awk '
        /^[[:space:]]*enable-auth[[:space:]]*=/ {
            sub(/^[^=]*=[[:space:]]*/, "")
            sub(/[[:space:]]+#.*$/, "")
            sub(/[[:space:]]+$/, "")
            if ($0 != "\"plain[passwd=/etc/ocserv/ocpasswd]\"") bad = 1
            count++
        }
        END { exit (bad || count > 1) }
    ' "$1"
}

radius_ocserv_config_ready() {
    awk -v method="$2" '
        function trim(value) {
            sub(/^[[:space:]]+/, "", value)
            sub(/[[:space:]]+$/, "", value)
            return value
        }
        function invalid(message, line) {
            if (line) printf "%s:%d: %s\n", FILENAME, line, message
            else printf "%s: %s\n", FILENAME, message
            failed = 1
        }
        function validate_radius(key, value,   options, option, option_count, i, configs, groupconfigs) {
            if (value !~ /^radius\[.+\]$/ || value ~ /"/) {
                invalid(key " must use radius[config=/absolute/path,...]", FNR)
                return
            }
            option_count = split(substr(value, 8, length(value) - 8), options, ",")
            for (i = 1; i <= option_count; i++) {
                option = trim(options[i])
                if (option ~ /^config=/) {
                    configs++
                    if (option !~ /^config=\/.+/)
                        invalid(key " requires an absolute path in config=", FNR)
                }
                if (key == "auth" && option ~ /^groupconfig=/) {
                    groupconfigs++
                    if (option != "groupconfig=" required_groupconfig)
                        invalid("auth requires groupconfig=" required_groupconfig, FNR)
                }
            }
            if (configs != 1) invalid(key " requires exactly one config= option", FNR)
            if (key == "auth" && groupconfigs != 1)
                invalid("auth requires exactly one groupconfig=" required_groupconfig " option", FNR)
        }
        BEGIN { required_groupconfig = (method == "radius-certificate") ? "false" : "true" }
        /^[[:space:]]*(#|$)/ { next }
        /^[[:space:]]*\[vhost[[:space:]]*:/ {
            invalid("RADIUS requires the default Ocserv virtual host", FNR)
            next
        }
        /=/ {
            key = trim(substr($0, 1, index($0, "=") - 1))
            value = substr($0, index($0, "=") + 1)
            sub(/[[:space:]]+#.*$/, "", value)
            value = trim(value)
            if (value ~ /^".*"$/) value = substr(value, 2, length(value) - 2)
            if (key == "auth" || key == "acct") {
                if (++count[key] > 1) invalid("duplicate " key " directive", FNR)
                validate_radius(key, value)
            } else if (method == "radius" && (key == "config-per-user" || key == "config-per-group") && value != "") {
                invalid(key " conflicts with groupconfig=true in RADIUS-only mode", FNR)
            } else if (key == "enable-auth") {
                if (++count[key] > 1 || method != "radius-certificate" || value != "certificate")
                    invalid("the only supported alternative is enable-auth = certificate", FNR)
            } else if (key == "connect-script" && method == "radius" && value ~ /portal-connect-check/) {
                invalid("the managed certificate connection hook requires enable-auth = certificate", FNR)
            }
        }
        END {
            if (!count["auth"]) invalid("missing auth directive")
            if (!count["acct"]) invalid("missing acct directive")
            if (method == "radius-certificate" && !count["enable-auth"])
                invalid("missing enable-auth = certificate")
            exit failed
        }
    ' "$1" >&2
}
