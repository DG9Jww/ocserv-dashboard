#!/usr/bin/env bash

ocserv_auth_method() {
    awk '
        /^[[:space:]]*auth[[:space:]]*=/ {
            count++
            sub(/^[^=]*=[[:space:]]*/, "")
            sub(/#.*/, "")
            sub(/[[:space:]]+$/, "")
            if ($0 ~ /^"certificate"$/ || $0 == "certificate") method = "certificate"
            else if ($0 ~ /^"radius\[.*\]"$/ || $0 ~ /^radius\[.*\]$/) method = "radius"
        }
        /^[[:space:]]*enable-auth[[:space:]]*=/ {
            alternatives++
            sub(/^[^=]*=[[:space:]]*/, "")
            sub(/#.*/, "")
            sub(/[[:space:]]+$/, "")
            if ($0 ~ /^"certificate"$/ || $0 == "certificate") certificate++
        }
        END {
            if (count != 1 || method == "") exit 1
            if (method == "radius" && alternatives) {
                if (alternatives != 1 || certificate != 1) exit 1
                method = "radius-certificate"
            }
            print method
        }
    ' "$1"
}

# Remove the password fallback from configurations generated by older releases.
# A custom fallback requires an explicit edit before switching authentication.
certificate_ocserv_config_ready() {
    awk '
        /^[[:space:]]*enable-auth[[:space:]]*=/ {
            sub(/^[^=]*=[[:space:]]*/, "")
            sub(/[[:space:]]+#.*$/, "")
            sub(/[[:space:]]+$/, "")
            if ($0 != "\"plain[passwd=/etc/ocserv/ocpasswd]\"") bad = 1
            count++
        }
        END { exit (bad || count > 1) }
    ' "$1"
}

radius_ocserv_config_ready() {
    awk -v method="$2" '
        /^[[:space:]]*(#|$)/ { next }
        /^[[:space:]]*\[vhost[[:space:]]*:/ { bad = 1 }
        {
            key = $0
            sub(/=.*/, "", key)
            gsub(/^[[:space:]]+|[[:space:]]+$/, "", key)
            value = $0
            sub(/^[^=]*=[[:space:]]*/, "", value)
            sub(/[[:space:]]+#.*$/, "", value)
            sub(/[[:space:]]+$/, "", value)
            if (key == "auth" || key == "acct") {
                count[key]++
                if (value !~ /^"radius\[config=\/[^"]+\]"$/) bad = 1
                if (key == "auth" && value !~ /,groupconfig=true[,\]]/) bad = 1
            }
            if (key == "enable-auth") {
                count[key]++
                if (method != "radius-certificate" || value !~ /^("certificate"|certificate)$/) bad = 1
            }
            if (method == "radius" && key == "connect-script" && value ~ /portal-connect-check/)
                bad = 1
        }
        END {
            exit (bad || count["auth"] != 1 || count["acct"] != 1 ||
                (method == "radius-certificate" && count["enable-auth"] != 1))
        }
    ' "$1"
}
